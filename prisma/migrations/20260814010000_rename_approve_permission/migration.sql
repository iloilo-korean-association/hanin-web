-- 권한 이름 변경: '승인권' → '확인권'
--
-- 사전 승인 절차(요청 → 결재 → 집행)를 없앴다. 그 권한이 이제 하는 일은
-- **장부에 적힌 뒤** 감사 확인 도장을 찍는 것이다(Transaction.reviewedBy).
-- 이름을 그대로 두면 다음 총무가 "결재를 기다려야 하나" 하고 멈춘다.
--
-- Officer.permissions 는 쉼표로 이어 붙인 문자열 한 칸이다(스키마에 enum 이 없다).
-- replace 로 부분 치환하면 '승인권,조회권' → '확인권,조회권' 이 된다.
-- 다른 권한 이름에 '승인권' 이 부분 문자열로 들어 있는 것은 없다(업소관리·행사관리·
-- 서비스관리·연락처관리·회원관리·임원관리·조회권·입력권) — 오염되지 않는다.

UPDATE "Officer"
SET "permissions" = replace("permissions", '승인권', '확인권')
WHERE "permissions" LIKE '%승인권%';
